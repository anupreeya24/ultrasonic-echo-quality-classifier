import fs from 'node:fs';
import assert from 'node:assert/strict';
import {trainAndEvaluate,evaluate} from './docs/forest.mjs';
const samples=JSON.parse(fs.readFileSync('docs/training-samples.json'));
const model=JSON.parse(fs.readFileSync('docs/model.json'));
assert.equal(model.trees.length,10);assert.equal(model.features.length,11);
for(const s of samples)assert.equal(s.label,s.originalLabel);
const test=samples.filter(s=>s.partition==='test');
for(const label of model.classes)assert.equal(test.filter(s=>s.label===label).length,15);
const result=trainAndEvaluate(samples);assert.equal(result.generatedCount,0);
assert.deepEqual(result.evaluation,evaluate(model,test));
const altered=samples.map(s=>s.partition==='test'?{...s,label:model.classes[(model.classes.indexOf(s.label)+1)%3]}:s);
assert.deepEqual(trainAndEvaluate(altered).model,result.model);
assert.ok(!fs.readFileSync('docs/live.js','utf8').includes('trainingLabel'));
console.log('Recorded labels, three-class test coverage, 10 trees, no generated data, and held-out-label isolation passed.');
