import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {predict} from './docs/forest.mjs';
const elements=new Map();
const element=()=>({textContent:'',value:'',disabled:false,listeners:{},addEventListener(name,fn){this.listeners[name]=fn},replaceChildren(){},append(){},setAttribute(){}});
const context={document:{getElementById(id){if(!elements.has(id))elements.set(id,element());return elements.get(id)},createElement:element,createElementNS:element},navigator:{},fetch:()=>new Promise(()=>{}),setInterval(){},console,TextDecoder};
vm.createContext(context);
vm.runInContext(fs.readFileSync('docs/crosscheck.js','utf8'),context);
vm.runInContext(fs.readFileSync('docs/training-support.js','utf8'),context);
vm.runInContext(fs.readFileSync('docs/live.js','utf8'),context);
const model=JSON.parse(fs.readFileSync('docs/model.json','utf8'));
context.testModel=model;
vm.runInContext('liveModel=testModel',context);
const reference=JSON.parse(fs.readFileSync('docs/training-samples.json','utf8'));
reference.forEach(({x:features})=>{context.testFeatures=features;const p=vm.runInContext('forestProbabilities(testModel,testFeatures)',context),expected=predict(model,features);p.forEach((v,i)=>assert.ok(Math.abs(v-expected[i])<1e-12));assert.ok(Math.abs(p.reduce((a,b)=>a+b,0)-1)<1e-12);});
let extracted=vm.runInContext('sessionFeatures([{distance:10,valid:1},{distance:20,valid:1},{distance:0,valid:0}])',context);
assert.equal(extracted[0],2/3);assert.equal(extracted[1],15);assert.equal(extracted[2],5);assert.equal(extracted[5],15);assert.equal(extracted[6],5);
for(let i=0;i<30;i++)vm.runInContext(`acceptLine('live_1,${i},1750,30,1')`,context);
assert.ok(model.classes.map(s=>s.replaceAll('_',' ')).includes(elements.get('prediction').textContent));
elements.get('actual-label').value=vm.runInContext('lastCompleted.predicted',context);
elements.get('save-check').listeners.click();
assert.ok(elements.get('live-accuracy').textContent.startsWith('100.0%'));
elements.get('save-check').listeners.click();
assert.equal(vm.runInContext('checkedSessions.length',context),1);
for(let i=0;i<30;i++)if(i!==6)vm.runInContext(`acceptLine('live_2,${i},1750,30,1')`,context);
assert.equal(elements.get('prediction').textContent,'Collecting…');
assert.ok(elements.get('live-status').textContent.includes('skipping'));
for(let i=0;i<30;i++)vm.runInContext(`acceptLine('live_3,${i},0,0,0')`,context);
assert.ok(model.classes.map(s=>s.replaceAll('_',' ')).includes(elements.get('prediction').textContent));
elements.get('actual-label').value=vm.runInContext('liveModel.classes.find(c=>c!==lastCompleted.predicted)',context);
elements.get('save-check').listeners.click();
assert.ok(elements.get('live-accuracy').textContent.startsWith('50.0%'));
console.log('90 model reference comparisons, feature extraction, live classification, missing-reading handling, and no-echo session passed.');
